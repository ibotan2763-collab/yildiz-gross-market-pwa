create or replace function public.is_admin() returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.profiles where id=auth.uid() and role='admin');
$$;

drop policy if exists "profiles own read" on public.profiles; create policy "profiles own read" on public.profiles for select using(id=auth.uid() or public.is_admin());
drop policy if exists "profiles own insert" on public.profiles; create policy "profiles own insert" on public.profiles for insert with check(id=auth.uid());
drop policy if exists "profiles own update" on public.profiles; create policy "profiles own update" on public.profiles for update using(id=auth.uid()) with check(id=auth.uid());
drop policy if exists "addresses own" on public.addresses; create policy "addresses own" on public.addresses for all using(user_id=auth.uid() or public.is_admin()) with check(user_id=auth.uid() or public.is_admin());
drop policy if exists "categories public read" on public.categories; create policy "categories public read" on public.categories for select using(active=true or public.is_admin());
drop policy if exists "categories admin write" on public.categories; create policy "categories admin write" on public.categories for all using(public.is_admin()) with check(public.is_admin());
drop policy if exists "products public read" on public.products; create policy "products public read" on public.products for select using(active=true or public.is_admin());
drop policy if exists "products admin write" on public.products; create policy "products admin write" on public.products for all using(public.is_admin()) with check(public.is_admin());
drop policy if exists "orders own read" on public.orders; create policy "orders own read" on public.orders for select using(user_id=auth.uid() or public.is_admin());
drop policy if exists "orders own insert" on public.orders; create policy "orders own insert" on public.orders for insert with check(user_id=auth.uid());
drop policy if exists "orders admin update" on public.orders; create policy "orders admin update" on public.orders for update using(public.is_admin());
drop policy if exists "items own read" on public.order_items; create policy "items own read" on public.order_items for select using(exists(select 1 from public.orders o where o.id=order_id and (o.user_id=auth.uid() or public.is_admin())));
drop policy if exists "items own insert" on public.order_items; create policy "items own insert" on public.order_items for insert with check(exists(select 1 from public.orders o where o.id=order_id and o.user_id=auth.uid()));

