create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '', phone text not null default '', role text not null default 'customer' check(role in ('customer','admin')),
  created_at timestamptz not null default now()
);
create table if not exists public.addresses (
  id uuid primary key default gen_random_uuid(), user_id uuid not null references auth.users(id) on delete cascade,
  title text not null default 'Ev', address text not null, is_default boolean not null default true, created_at timestamptz not null default now()
);
create table if not exists public.categories (
  id bigint generated by default as identity primary key, name text not null unique, emoji text default '🛒', sort_order int default 0, active boolean default true
);
create table if not exists public.products (
  id bigint generated by default as identity primary key, name text not null, category_id bigint references public.categories(id) on delete set null,
  emoji text default '🛒', image_url text, old_price numeric(12,2), price numeric(12,2) not null check(price>=0), stock int not null default 0,
  active boolean not null default true, featured boolean not null default false, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(), user_id uuid not null references auth.users(id), address_id uuid references public.addresses(id),
  customer_name text not null, phone text not null, delivery_address text not null, payment_method text not null check(payment_method in ('Kapıda Nakit','Kapıda Kart')),
  total numeric(12,2) not null, status text not null default 'Sipariş Alındı', created_at timestamptz not null default now()
);
create table if not exists public.order_items (
  id bigint generated by default as identity primary key, order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id), product_name text not null, quantity int not null check(quantity>0), unit_price numeric(12,2) not null, line_total numeric(12,2) not null
);

